CREATE TABLE users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL,
    nickname varchar(50) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'USER'
        CHECK (role IN ('USER', 'ADMIN')),
    status varchar(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN')),
    email_verified boolean NOT NULL DEFAULT false,
    service_terms_agreed_at timestamptz NOT NULL,
    privacy_terms_agreed_at timestamptz NOT NULL,
    profile_media_id bigint UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_email_not_blank CHECK (btrim(email) <> ''),
    CONSTRAINT users_nickname_not_blank CHECK (btrim(nickname) <> '')
);

CREATE UNIQUE INDEX users_email_lower_uq ON users (lower(email));

-- Administrators can add programming languages without changing a CHECK constraint.
CREATE TABLE languages (
    language_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(30) NOT NULL UNIQUE,
    name varchar(50) NOT NULL UNIQUE,
    display_order integer NOT NULL UNIQUE CHECK (display_order > 0),
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT languages_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT languages_name_not_blank CHECK (btrim(name) <> '')
);

