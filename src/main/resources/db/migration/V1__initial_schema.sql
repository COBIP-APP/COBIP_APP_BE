-- Root rows are app areas; children are filters such as cache/DB/network/log.
CREATE TABLE categories (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_category_id bigint REFERENCES categories (category_id),
    code varchar(50) NOT NULL UNIQUE,
    name varchar(50) NOT NULL,
    display_order integer NOT NULL CHECK (display_order > 0),
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT categories_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT categories_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT categories_not_own_parent CHECK (parent_category_id IS DISTINCT FROM category_id)
);

CREATE UNIQUE INDEX categories_root_name_uq ON categories (name)
    WHERE parent_category_id IS NULL;
CREATE UNIQUE INDEX categories_child_name_uq ON categories (parent_category_id, name)
    WHERE parent_category_id IS NOT NULL;
CREATE UNIQUE INDEX categories_root_order_uq ON categories (display_order)
    WHERE parent_category_id IS NULL;
CREATE UNIQUE INDEX categories_child_order_uq ON categories (parent_category_id, display_order)
    WHERE parent_category_id IS NOT NULL;

